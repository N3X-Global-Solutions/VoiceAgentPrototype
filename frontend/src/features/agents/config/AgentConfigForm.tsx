import { useEffect, useRef, useState } from 'react'
import { Icon } from '@/components/Icon'
import { Badge, Field, IconChip, Section, Spinner, Toggle } from '@/components/ui'
import { api, type AgentConfig, type Catalog, type Health, type HttpTool, type PartKind, type ProviderId } from '@/lib/api'
import {
  CROSS_LANGUAGE_VOICES,
  PART_KEY,
  SOURCE_LABEL,
  callLanguages,
  defaultVoice,
  hasFeature,
  partPriceSource,
  partPriceText,
  providerName,
  providersFor,
  switchProvider,
  voiceFits,
  voicesFor,
} from '@/lib/providers'
import type { ConfigTab } from './tabs'
import { ToolEditor } from './ToolEditor'

// Fixed phrases the agent speaks as written (not generated by the LLM), so they must be
// in the agent's language.
const PHRASES = ['greeting', 'goodbye_message', 'nudge_message', 'repeat_message'] as const

// True when the text has letters but none from an Indic script, i.e. it is still English.
function looksEnglish(text: string) {
  return /[A-Za-z]/.test(text) && !/[ऀ-෿]/.test(text)
}

const PART_INFO: { kind: PartKind; icon: 'mic' | 'brain' | 'headphones'; title: string; description: string }[] = [
  { kind: 'stt', icon: 'mic', title: 'Speech recognition', description: "Turns the caller's speech into text." },
  { kind: 'llm', icon: 'brain', title: 'AI model', description: 'Writes the agent\'s replies and calls its tools.' },
  { kind: 'tts', icon: 'headphones', title: 'Voice', description: 'Speaks the replies. Its languages and voices fill the Voice tab.' },
]

const EMPTY_TOOL: HttpTool = {
  name: '',
  description: '',
  method: 'POST',
  url: 'https://',
  headers: {},
  parameters: {},
  required: [],
  timeout_secs: 8,
}

type Props = {
  catalog: Catalog
  health?: Health | null
  value: AgentConfig
  onChange: (config: AgentConfig) => void
  tab: ConfigTab
}

/** The agent's configuration, one sub-tab at a time. */
export function AgentConfigForm({ catalog, health, value, onChange, tab }: Props) {
  const set = <K extends keyof AgentConfig>(key: K, v: AgentConfig[K]) => onChange({ ...value, [key]: v })
  const latest = useRef(value)
  useEffect(() => {
    latest.current = value
  }, [value])
  const [translating, setTranslating] = useState<{ busy: boolean; text: string } | null>(null)
  const [providerNote, setProviderNote] = useState<string | null>(null)

  const translatePhrases = async (language: string) => {
    const name = catalog.languages[language]
    setTranslating({ busy: true, text: `Translating the greeting and messages to ${name}…` })
    try {
      const texts = Object.fromEntries(PHRASES.map((k) => [k, latest.current[k]]))
      const res = await api.translate(language, texts)
      onChange({ ...latest.current, ...res.texts })
      setTranslating({ busy: false, text: `Translated to ${name}. Review the greeting and call messages, then save.` })
    } catch (e) {
      setTranslating({ busy: false, text: `Translation failed: ${e instanceof Error ? e.message : e}` })
    }
  }
  const englishPhrases = value.language !== 'en-IN' && PHRASES.some((k) => looksEnglish(value[k]))

  // The voice provider's voices for this language: its own first, then the cross-language ones.
  const voices = voicesFor(catalog, value.tts_provider, value.language)
  const languages = callLanguages(catalog, value.stt_provider, value.tts_provider)
  const sttName = providerName(catalog, value.stt_provider)
  const ttsName = providerName(catalog, value.tts_provider)
  const voiceGroups = [...new Set(voices.map((v) => v.group))]

  const changeLanguage = (language: string) => {
    const stillValid = catalog.voices.some((v) => v.provider === value.tts_provider && v.id === value.voice && voiceFits(v, language))
    // A language with no voices of its own (Sarvam Malayalam) falls back to a cross-language voice.
    const firstVoice = defaultVoice(catalog, value.tts_provider, language) ?? value.voice
    const next = { ...value, language, voice: stillValid ? value.voice : firstVoice }
    onChange(next)
    latest.current = next
    if (language !== 'en-IN' && PHRASES.some((k) => looksEnglish(next[k]))) void translatePhrases(language)
  }

  const languageName = catalog.languages[value.language]

  const translateAlert = (englishPhrases || translating) && (
    <div className="inline-alert">
      {translating?.busy ? <Spinner /> : <Icon name="globe" />}
      <span className="grow">
        {translating?.busy || !englishPhrases
          ? translating?.text
          : `The greeting or call messages are still in English, so the agent will say them in English.`}
      </span>
      {englishPhrases && !translating?.busy && (
        <button type="button" className="btn btn-secondary btn-sm" onClick={() => translatePhrases(value.language)}>
          Translate to {languageName}
        </button>
      )}
    </div>
  )

  if (tab === 'prompt') {
    return (
      <>
        <Section icon="chat" title="Greeting" description="The first thing the agent says when the call connects, spoken exactly as written." single>
          <Field label="Opening line">
            <textarea rows={2} value={value.greeting} onChange={(e) => set('greeting', e.target.value)} />
          </Field>
          {translateAlert}
        </Section>
        <Section
          icon="brain"
         
          title="Instructions"
          description="Persona, objective, business context, guardrails and conversation steps. Write it in English for any language: the agent replies in its configured language."
          single
        >
          <Field label="System prompt">
            <textarea
              className="prompt"
              rows={18}
              value={value.instructions}
              onChange={(e) => set('instructions', e.target.value)}
              placeholder={'You are Riya, a friendly support agent for Acme Store.\n\n## Objective\n…\n\n## Guardrails\n…'}
            />
          </Field>
          <span className="char-count">
            {value.instructions.length.toLocaleString()} characters · ~{Math.ceil(value.instructions.length / 4).toLocaleString()} tokens
          </span>
        </Section>
      </>
    )
  }

  if (tab === 'providers') {
    const choose = (kind: PartKind, id: ProviderId) => {
      if (value[PART_KEY[kind]] === id) return
      const res = switchProvider(catalog, value, kind, id)
      onChange(res.config)
      latest.current = res.config
      setProviderNote(res.note ?? null)
    }
    return (
      <>
        {providerNote && (
          <div className="banner tone-amber" style={{ margin: '0 0 4px' }}>
            <Icon name="alert" /> <span className="grow">{providerNote}</span>
            <button type="button" className="btn btn-ghost btn-sm" onClick={() => setProviderNote(null)} aria-label="Dismiss">
              <Icon name="x" size={14} />
            </button>
          </div>
        )}
        {PART_INFO.map(({ kind, icon, title, description }) => (
          <Section key={kind} icon={icon} title={title} description={description} single>
            <div className="choice-cards providers">
              {providersFor(catalog, kind).map((p) => {
                const part = p[kind]!
                const active = value[PART_KEY[kind]] === p.id
                const source = partPriceSource(part)
                const keyMissing = health?.providers ? !health.providers[p.id] : !p.configured
                return (
                  <button key={p.id} type="button" className={`choice${active ? ' active' : ''}`} onClick={() => choose(kind, p.id)}>
                    <div className="choice-body">
                      <strong>{p.name}</strong>
                      <span className="desc">{kind === 'tts' ? `${catalog.voices.filter((v) => v.provider === p.id).length} voices · ` : ''}{part.languages.length ? `${part.languages.length} languages` : part.model}</span>
                      <span className="choice-price" title={source ? SOURCE_LABEL[source] : undefined}>
                        {partPriceText(part)}
                        {source && source !== 'published' && <span className={`price-flag ${source}`}>{source === 'estimate' ? 'estimate' : 'quoted'}</span>}
                      </span>
                      {part.note && <span className="desc">{part.note}</span>}
                      {keyMissing && (
                        <Badge tone="amber" icon="lock">
                          {p.key_env} not set
                        </Badge>
                      )}
                    </div>
                  </button>
                )
              })}
            </div>
          </Section>
        ))}
        <p className="muted small provider-footnote">
          Each call is billed at the rates of the providers chosen here (INR, before GST), and the call log shows the cost of each part. Rates marked{' '}
          <span className="price-flag estimate">estimate</span> aren't published: set the real ones in the server's .env (Settings → Cost rates).
        </p>
      </>
    )
  }

  if (tab === 'voice') {
    return (
      <>
        <Section
          icon="globe"
          title="Language"
          description={
            value.stt_provider === value.tts_provider
              ? `The agent understands and replies in this language. Showing the ${languages.length} languages ${sttName} supports.`
              : `The agent understands and replies in this language. Showing the ${languages.length} languages both ${sttName} (speech recognition) and ${ttsName} (voice) support.`
          }
        >
          <Field label="Primary language">
            <select value={value.language} onChange={(e) => changeLanguage(e.target.value)}>
              {languages.map((code) => (
                <option key={code} value={code}>
                  {catalog.languages[code]} ({code})
                </option>
              ))}
            </select>
          </Field>
          <div className="field" style={{ justifyContent: 'flex-end' }}>
            <Toggle
              checked={value.auto_detect_language}
              onChange={(v) => set('auto_detect_language', v)}
              label="Follow the caller's language"
              hint={`Reply in whatever language the caller speaks, instead of always ${languageName}.`}
            />
          </div>
          {translateAlert}
        </Section>
        <Section icon="headphones" title="Voice" description={`The voice the agent speaks with, from ${ttsName}. Change the provider in the Providers tab.`}>
          <Field label="Speaker" hint={`${voices.length} ${ttsName} voices available for ${languageName}`}>
            <select value={value.voice} onChange={(e) => set('voice', e.target.value)}>
              {voiceGroups.map((group) => (
                <optgroup key={group} label={group}>
                  {voices
                    .filter((v) => v.group === group)
                    .map((v) => (
                      <option key={v.id} value={v.id}>
                        {v.name} · {v.style}
                        {v.group === 'Hindi-English Code-Mixed' ? ' (Hinglish)' : ''}
                        {v.provider === 'sarvam' && v.language !== value.language && CROSS_LANGUAGE_VOICES.includes(v.id) ? ' (English voice, test)' : ''}
                      </option>
                    ))}
                </optgroup>
              ))}
            </select>
          </Field>
          <Field
            label={
              <>
                Speaking pace <span className="value">{value.pace.toFixed(2)}×</span>
              </>
            }
            hint={value.tts_provider === 'gnani' ? '1.00× is natural speed. Gnani rounds to the speeds its voice model supports.' : '1.00× is natural speed.'}
          >
            <input type="range" min={0.5} max={2} step={0.05} value={value.pace} onChange={(e) => set('pace', Number(e.target.value))} />
          </Field>
        </Section>
      </>
    )
  }

  if (tab === 'speech') {
    const robustAvailable = hasFeature(catalog, value.stt_provider, 'robust_turns')
    return (
      <>
        <Section icon="zap" title="Turn detection" description="How the agent decides the caller has finished speaking." single>
          <div className="choice-cards">
            <button type="button" className={`choice${value.turn_detection === 'fast' || !robustAvailable ? ' active' : ''}`} onClick={() => set('turn_detection', 'fast')}>
              <IconChip icon="zap" />
              <div>
                <strong>Fast</strong>
                <span className="desc">Our server detects the pause. Replies in about 1.2–1.4 s.</span>
              </div>
            </button>
            <button
              type="button"
              className={`choice${value.turn_detection === 'sarvam' && robustAvailable ? ' active' : ''}`}
              onClick={() => set('turn_detection', 'sarvam')}
              disabled={!robustAvailable}
            >
              <IconChip icon="wave" />
              <div>
                <strong>Robust</strong>
                <span className="desc">
                  {robustAvailable
                    ? 'The speech engine detects the pause. Best on noisy lines, about 2.3 s.'
                    : `Needs Sarvam speech recognition. ${sttName} always uses Fast.`}
                </span>
              </div>
            </button>
          </div>
        </Section>
        <Section icon="mic" title="Recognition" description={`Fine-tune how ${sttName} recognises the caller's speech.`}>
          <Field label="End-of-turn pause" hint="Shorter is faster, but may cut off callers who pause mid-sentence.">
            <select value={value.end_of_speech_ms ?? ''} onChange={(e) => set('end_of_speech_ms', e.target.value ? Number(e.target.value) : null)}>
              <option value="">{value.turn_detection === 'fast' || !robustAvailable ? 'Default (300 ms)' : 'Default (engine decides)'}</option>
              {[200, 250, 300, 400, 500, 700, 1000].map((v) => (
                <option key={v} value={v}>
                  {v} ms
                </option>
              ))}
            </select>
          </Field>
          <Field label="Important words" hint="Names, brands and products the recognizer should favour. Comma separated.">
            <input
              value={value.important_words.join(', ')}
              placeholder="Acme, Riya, EMI"
              onChange={(e) =>
                set(
                  'important_words',
                  e.target.value
                    .split(',')
                    .map((w) => w.trimStart())
                    .filter((w, i, all) => w || i === all.length - 1),
                )
              }
            />
          </Field>
        </Section>
      </>
    )
  }

  if (tab === 'call') {
    return (
      <>
        <Section icon="sparkle" title="Behaviour" description="How the model responds and when the call ends.">
          <Field
            label={
              <>
                Creativity (temperature) <span className="value">{value.temperature.toFixed(2)}</span>
              </>
            }
            hint="Lower keeps answers consistent and on-script."
          >
            <input type="range" min={0} max={1} step={0.05} value={value.temperature} onChange={(e) => set('temperature', Number(e.target.value))} />
          </Field>
          <div className="field">
            <Toggle
              checked={value.end_call_enabled}
              onChange={(v) => set('end_call_enabled', v)}
              label="Agent can end the call"
              hint="Hangs up by itself once the conversation is done."
            />
          </div>
        </Section>
        <Section icon="timer" title="Limits" description="Guards that apply to every call this agent takes.">
          <Field label="Maximum call length" hint="In seconds. The server-wide cap still applies.">
            <input type="number" min={30} max={1800} value={value.max_call_seconds} onChange={(e) => set('max_call_seconds', Number(e.target.value))} />
          </Field>
          <Field label="Silence before nudge" hint="In seconds. The agent checks in, then hangs up if the line stays silent.">
            <input type="number" min={4} max={60} value={value.idle_timeout_secs} onChange={(e) => set('idle_timeout_secs', Number(e.target.value))} />
          </Field>
        </Section>
        <Section icon="chat" title="Call messages" description="Fixed phrases spoken exactly as written.">
          {translateAlert}
          <Field label="Goodbye message" wide>
            <input value={value.goodbye_message} onChange={(e) => set('goodbye_message', e.target.value)} />
          </Field>
          <Field label="Nudge when the caller is silent">
            <input value={value.nudge_message} onChange={(e) => set('nudge_message', e.target.value)} />
          </Field>
          <Field label="Ask to repeat (if a reply fails)">
            <input value={value.repeat_message} onChange={(e) => set('repeat_message', e.target.value)} />
          </Field>
        </Section>
      </>
    )
  }

  return (
    <Section
      icon="wrench"
     
      title="Tools"
      description="Your HTTP APIs the agent can call mid-conversation, for example to look up an order."
      aside={
        <button type="button" className="btn btn-soft btn-sm" onClick={() => set('tools', [...value.tools, { ...EMPTY_TOOL }])}>
          <Icon name="plus" size={14} /> Add tool
        </button>
      }
    >
      {value.tools.length === 0 && (
        <div className="empty">
          No tools yet. To try one, add a POST tool pointing at the demo endpoint <code>http://localhost:7860/api/demo/order-status</code> with an{' '}
          <code>order_id</code> parameter.
        </div>
      )}
      {value.tools.map((tool, i) => (
        <ToolEditor
          key={i}
          tool={tool}
          onChange={(t) => set('tools', value.tools.map((x, j) => (j === i ? t : x)))}
          onRemove={() => set('tools', value.tools.filter((_, j) => j !== i))}
        />
      ))}
    </Section>
  )
}
